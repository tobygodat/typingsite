function isTag<K extends keyof HTMLElementTagNameMap>(node: HTMLElement, tag: K): node is HTMLElementTagNameMap[K] {
  return node.localName === tag;
}

export function applicationElement<K extends keyof typeof HOST_TAGS>(id: K) {
  const node = document.getElementById(id);

  if (!node || !isTag(node, HOST_TAGS[id])) throw new Error(`Missing application host ${id}`);

  return node;
}
